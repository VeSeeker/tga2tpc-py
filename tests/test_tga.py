"""TGA decoder tests covering the variants tga2tpc supports."""

from __future__ import annotations

import struct

import numpy as np
import pytest

from tga2tpc.tga import TGAError, decode_tga, load_tga

from .helpers import (
    make_grey_tga,
    make_indexed_tga,
    make_rgb16_tga,
    make_truecolour_tga,
    tga_header,
    write_tga_bytes,
)

ORIGINS = ["BL", "BR", "UL", "UR"]


@pytest.mark.parametrize("origin", ORIGINS)
@pytest.mark.parametrize("depth", [24, 32])
@pytest.mark.parametrize("rle", [False, True])
def test_truecolour_origins_and_rle(tmp_path, origin, depth, rle):
    case = make_truecolour_tga(
        tmp_path / f"rgb{depth}_{origin}_{rle}.tga",
        7 if rle else 5,
        5 if rle else 3,
        depth,
        origin=origin,
        rle=rle,
    )
    image = load_tga(case.path)
    assert image.width == case.width
    assert image.height == case.height
    assert image.pixel_depth == depth
    assert image.image_type == case.image_type
    assert image.origin == origin
    np.testing.assert_array_equal(image.pixels, case.expected)


@pytest.mark.parametrize("origin", ORIGINS)
@pytest.mark.parametrize("rle", [False, True])
@pytest.mark.parametrize("attribute_bits", [0, 8])
def test_rgb16_expansion_and_alpha(tmp_path, origin, rle, attribute_bits):
    case = make_rgb16_tga(
        tmp_path / f"rgb16_{origin}_{rle}_{attribute_bits}.tga",
        6 if rle else 5,
        4,
        origin=origin,
        rle=rle,
        attribute_bits=attribute_bits,
    )
    image = load_tga(case.path)
    np.testing.assert_array_equal(image.pixels, case.expected)
    if attribute_bits:
        assert set(np.unique(image.pixels[:, :, 3])) <= {0, 255}


def test_8bit_truecolour_is_treated_as_greyscale(tmp_path):
    width, height = 4, 3
    values = [(x * 31 + y * 17) & 0xFF for y in range(height) for x in range(width)]
    pixels = [bytes((value,)) for value in values]
    expected = np.array(values, dtype=np.uint8).reshape(height, width)
    rgba = np.empty((height, width, 4), dtype=np.uint8)
    rgba[:, :, 0] = expected
    rgba[:, :, 1] = expected
    rgba[:, :, 2] = expected
    rgba[:, :, 3] = 255
    case = write_tga_bytes(
        tmp_path / "rgb8.tga",
        width=width,
        height=height,
        depth=8,
        file_pixels=pixels,
        file_rgba=rgba,
        image_type=2,
        origin="BL",
        rle=False,
    )
    np.testing.assert_array_equal(load_tga(case.path).pixels, case.expected)


